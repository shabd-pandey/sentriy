// Vercel builds each file in `api/` with its Node builder, which does not
// transpile or trace TypeScript imports that live outside `api/`. Re-exporting
// `backend/src/vercel.ts` from a `.ts` entry therefore produced:
//
//   Cannot find module '/var/task/backend/src/vercel' imported from ...
//
// This script bundles the shared adapter (plus the worker it imports) into a
// single JavaScript function. `packages: "external"` keeps npm dependencies as
// bare imports, so Vercel's file tracing still installs them normally.
//
// The output is committed so a deploy is never dependent on build ordering,
// and regenerated on every `npm run build` so it cannot drift.
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { build } from "esbuild";

const scripts = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(scripts, "..");
const output = path.join(project, "api", "[...path].js");

// Two layouts use this script: the monorepo (`prototype/` plus a sibling
// `backend/`) and the standalone Vercel repo (`backend/` at the root).
const entries = [
  path.resolve(project, "..", "backend", "src", "vercel.ts"),
  path.resolve(project, "backend", "src", "vercel.ts"),
];
const entry = entries.find((candidate) => existsSync(candidate));

if (!entry) {
  console.error("build-api: could not find backend/src/vercel.ts next to", project);
  process.exit(1);
}

await build({
  entryPoints: [entry],
  outfile: output,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  packages: "external",
  legalComments: "none",
  logLevel: "info",
  banner: {
    js: "// Generated by scripts/build-api.mjs from backend/src/vercel.ts. Do not edit.",
  },
});
